import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const phase=process.argv[2];assert.ok(['identity','parser'].includes(phase));
const repo=new URL('../',import.meta.url);
const proof=JSON.parse(fs.readFileSync(new URL('.tmp/scholar-review-recovery-native-v1.json',repo),'utf8'));
const out=new URL(`.tmp/scholar-review-controller-${phase}-v1.json`,repo);assert.equal(fs.existsSync(out),false);
const source=await(await fetch('http://127.0.0.1:8887/catalog-review-workflow.js')).text();
assert.equal(source,fs.readFileSync(new URL('../RSTV4/src/rstv4/catalog_review_workflow.js',repo),'utf8'));
const host=vm.createContext({});vm.runInContext(source,host);
const requests=[],map=new Map();
const api=async(path,body)=>{const response=await fetch('http://127.0.0.1:8887'+path,body?{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)}:{});const value=await response.json();requests.push({path,status:response.status,body:value});if(!response.ok){const e=Error(JSON.stringify(value));e.status=response.status;throw e;}return value;};
const controller=host.CatalogReviewWorkflow.createController({api,makeKey:()=>`actual-review-${phase}-v1`,storage:{getItem:k=>map.get(k),setItem:(k,v)=>map.set(k,v)},namespace:'actual-software-native'});
const caseId=phase==='identity'?proof.file_version_id:proof.parser_job_id;
await controller.load(caseId);controller.setReason(`Explicit ${phase} review of owned software fixture; no scientific approval`);
if(phase==='parser')controller.addSelection(proof.reference_selection);
const receipt=await controller.submit(phase==='identity'?'APPROVE_IDENTITY':'RECHECK_PARSE');
assert.equal(receipt.result.status,phase==='identity'?'APPROVED_IDENTITY':'PARSE_RECHECK_QUEUED');
const body={...receipt.request};delete body.case_id;
const replay=await api(`/api/catalog/review/cases/${encodeURIComponent(caseId)}/actions`,body);assert.deepEqual(replay,receipt);
const result={status:'PASS_SHIPPED_EXPLICIT_REVIEW_CONTROLLER_WITH_REAL_HTTP',phase,root:proof.root,case_id:caseId,receipt,requests,browser_verified:false,scientific_approval:false};
fs.writeFileSync(out,JSON.stringify(result,null,2),{flag:'wx'});
console.log('Actual shipped review controller and exact original receipt passed:',phase);
